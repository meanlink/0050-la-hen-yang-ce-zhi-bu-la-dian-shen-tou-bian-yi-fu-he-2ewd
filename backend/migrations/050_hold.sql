-- 量具失准扣留：按修补台暂停受影响接缝的交接，补测达标后恢复。

ALTER TABLE wax_batches DROP CONSTRAINT IF EXISTS wax_batches_stage_check;
ALTER TABLE wax_batches ADD CONSTRAINT wax_batches_stage_check
    CHECK(stage IN('sampling','sealed','classified','released','recheck','held'));

ALTER TABLE wax_batches ADD COLUMN IF NOT EXISTS hold_epoch bigint NOT NULL DEFAULT 0;
ALTER TABLE wax_batches ADD COLUMN IF NOT EXISTS pre_hold_stage text;
ALTER TABLE wax_batches DROP CONSTRAINT IF EXISTS wax_batches_pre_hold_stage_check;
ALTER TABLE wax_batches ADD CONSTRAINT wax_batches_pre_hold_stage_check
    CHECK(pre_hold_stage IS NULL OR pre_hold_stage IN('sampling','sealed','classified','released','recheck'));

-- 每次写入读数都记录真实时钟，用于判断某道接缝是否已在扣留之后补测。
ALTER TABLE wax_readings ADD COLUMN IF NOT EXISTS recorded_at timestamptz NOT NULL DEFAULT clock_timestamp();

CREATE TABLE IF NOT EXISTS wax_holds(
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch text NOT NULL REFERENCES wax_batches(code),
    bench text NOT NULL CHECK(bench IN('A','B','C')),
    reason text NOT NULL CHECK(length(reason)>=6),
    manager text NOT NULL,
    epoch bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    cleared_at timestamptz,
    cleared_by text
);
CREATE INDEX IF NOT EXISTS wax_holds_batch ON wax_holds(batch,id);
-- 同一批次同一修补台只保留一条未解除的扣留，重试登记不会重复扣留。
CREATE UNIQUE INDEX IF NOT EXISTS wax_holds_active ON wax_holds(batch,bench) WHERE cleared_at IS NULL;

-- 补测覆盖前的原始读数留档，便于追查扣留前的计量。
CREATE TABLE IF NOT EXISTS wax_reading_history(
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch text NOT NULL,
    seam text NOT NULL,
    pass int NOT NULL,
    depth numeric(5,2) NOT NULL,
    recorded_at timestamptz NOT NULL,
    retired_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    retired_by text,
    retire_reason text
);
CREATE INDEX IF NOT EXISTS wax_reading_history_batch ON wax_reading_history(batch,seam);

-- 交接凭证保留多张：扣留恢复后重新签发的动作不会覆盖原放行记录。
ALTER TABLE wax_dispatch ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE wax_dispatch ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT clock_timestamp();
ALTER TABLE wax_dispatch DROP CONSTRAINT IF EXISTS wax_dispatch_pkey;
ALTER TABLE wax_dispatch ADD CONSTRAINT wax_dispatch_pkey PRIMARY KEY (id);
CREATE INDEX IF NOT EXISTS wax_dispatch_batch ON wax_dispatch(batch,id);
